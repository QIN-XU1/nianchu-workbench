#!/usr/bin/env node
// 工具/历练任务库.mjs —— 每个场景的多个历练任务（按轮次轮换）
//
// ══════════════════════════════════════════════════════════════════════
//  为什么需要多任务
// ══════════════════════════════════════════════════════════════════════
//  第一轮历练后发现的真问题：
//    9 个场景全部完成了任务、产出了真实文件（4-9 KB 不等），
//    但第二轮、第三轮派**同一个任务**时，
//    场景 agent 正确地判断「任务已完成，无需重做」→ 不再积累经验。
//
//  实测证据（第二轮后的回复）：
//    「任务已完成，四项产出都已落盘且通过复核，无需重做。」
//    「任务已在前几轮完成，交付物均在位且符合要求，无需重做。」
//    「这份复盘在上一轮已经完成，两份产物都在，无需重做。」
//
//  也就是说：**不是它们不干，是我给的活重复了。**
//
//  所以需要「任务库」——每个场景准备多个不同的任务，按轮次轮换，
//  每次都让它做一件**没做过的新事**，才能持续积累经验。
//
//  ══════════════════════════════════════════════════════════════════════
//  任务设计原则
// ══════════════════════════════════════════════════════════════════════
//    ① 必须是该场景职责范围内
//    ② 必须能用它能访问的素材完成
//    ③ 结果必须可验证（落到文件）
//    ④ **必须与前一轮不同**（这是关键）
//    ⑤ 难度递进：先盘点现状 → 再分析问题 → 再给方案
//
//  每个任务带 `id`，历练工具会记录「已派过哪些」，
//  下次自动挑没派过的。
// ══════════════════════════════════════════════════════════════════════

