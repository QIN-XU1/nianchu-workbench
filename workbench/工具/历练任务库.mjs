/** 给某个场景取任务（按轮次） */
export function tasksOf(scene) {
  return TASK_LIBRARY[scene] || [];
}

/** 所有有任务的场景 */
export function scenesWithTasks() {
  return Object.keys(TASK_LIBRARY);
}

/** 拼装完整任务文本（任务正文 + 强制写经验说明） */
export function buildPrompt(scene, round) {
  const list = tasksOf(scene);
  if (!list.length) return null;
  const idx = Math.min(round, list.length - 1);
  const t = list[idx];
  const rootPath = process.env.DSH_PROJECT_ROOT || '';
  let body = t.task;
  if (rootPath) body = body.replace(/<ROOT>/g, rootPath.replace(/\\/g, '/'));
  return {
    id: t.id,
    title: t.title,
    verify: t.verify,
    round: idx + 1,
    total: list.length,
    text: body + '\n' + EXP_FORMAT_HINT.join('\n'),
  };
}
