// ── 阶段 B：并发（纯读项）──
//  用 async 包一层，因为 runGuard 是同步 spawnSync。
//  这里用「同时起 N 个 child_process」的方式并发：
//  spawnSync 会阻塞事件循环，所以改用 spawn + Promise。
const { spawn } = await import('node:child_process');

function runGuardAsync(g) {
  return new Promise((resolve) => {
    const file = path.join(HERE, g.file);
    if (!fs.existsSync(file)) {
      resolve({ name: g.name, ok: false, exit: -1, out: '哨兵文件不存在: ' + g.file, diffs: [] });
      return;
    }
    const MAX_TRY = g.retry === false ? 1 : 2;
    let attempt = 0;

    const once = () => new Promise((res) => {
      const child = spawn(process.execPath, [file, ...(g.args || [])], {
        env: process.env,
        stdio: ['ignore', 'pipe', 'pipe'],
      });
      let out = '';
      const timer = setTimeout(() => { try { child.kill(); } catch { /* ignore */ } }, g.timeoutMs || 120000);
      child.stdout.on('data', (d) => { out += d; });
      child.stderr.on('data', (d) => { out += d; });
      child.on('close', (code) => { clearTimeout(timer); res({ status: code, out }); });
      child.on('error', (e) => { clearTimeout(timer); res({ status: -1, out: String(e && e.message) }); });
    });

    (async () => {
      let r = null;
      for (attempt = 1; attempt <= MAX_TRY; attempt++) {
        r = await once();
        if (r.status === 0) break;
        if (attempt < MAX_TRY) await new Promise((s) => setTimeout(s, 800));
      }
      const diffs = String(r.out || '').split(/\r?\n/).filter((l) => /XX |✗|FAIL|差异/.test(l)).slice(0, 8).map((s) => s.trim());
      resolve({
        name: g.name, ok: r.status === 0, exit: r.status, out: r.out, diffs,
        invariants: g.invs || 0, desc: g.desc || '',
      });
    })();
  });
}

