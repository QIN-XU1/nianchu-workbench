function runGuard(g, verbose) {
  const file = path.join(HERE, g.file);
  if (!fs.existsSync(file)) {
    return { name: g.name, ok: false, exit: -1, out: '哨兵文件不存在: ' + g.file, diffs: [] };
  }

  // ══════════════════════════════════════════════════════════════
  //  ★ 2026-11-11：加一次重试
  //
  //  为什么：有些检查依赖**外部环境**，不是纯代码逻辑。
  //  典型是「界面回归」—— 它要截图，需要工作台窗口在前台。
  //  但体检串行跑 48 个工具，前面的工具可能把窗口状态弄乱
  //  （比如某个工具启动/关闭了 Electron），
  //  导致截图那一刻窗口不在前台 → 判 FAIL。
  //
  //  实测：单独跑界面回归 3/3 全通过，但体检里 100% FAIL。
  //  ⇒ 不是代码缺陷，是**检查之间的环境干扰**。
  //
  //  判据：如果真的坏了，重试还是会失败；
  //        如果只是环境干扰，重试一次就过。
  //        **重试不能掩盖真问题**，只能吸收偶发。
  // ══════════════════════════════════════════════════════════════
  const MAX_TRY = g.retry === false ? 1 : 2;
  let r = null;
  let out = '';
  let attempt = 0;

  for (attempt = 1; attempt <= MAX_TRY; attempt++) {
    r = spawnSync(process.execPath, [file, ...(g.args || [])], {
      encoding: 'utf8',
      timeout: g.timeoutMs || 120000,
      env: process.env,
    });
    out = (r.stdout || '') + (r.stderr || '');
    if (r.status === 0) break;

    // 只在第一次失败时重试，且要等一下让环境恢复
    if (attempt < MAX_TRY) {
      try {
        spawnSync(process.execPath, ['-e', 'setTimeout(()=>{},2500)'], { timeout: 6000 });
      } catch { /* ignore */ }
    }
  }

  const lines = out.split('\n');
  // 提取差异项（以 "  - " 开头的行）
  const diffs = lines.filter((l) => l.startsWith('  - ')).map((l) => l.slice(4));

  return {
    name: g.name,
    ok: r.status === 0,
    exit: r.status,
    out,
    diffs,
    attempts: attempt,
    retried: attempt > 1,
  };
}

