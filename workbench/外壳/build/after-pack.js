// ══════════════════════════════════════════════════════════════════════
//  electron-builder afterPack 钩子（2026-11-13 加）
// ══════════════════════════════════════════════════════════════════════
//
//  为什么需要这个钩子
//  ──────────────────────────────────────────────────────────────────
//  打包出的 exe 直接双击起不来。原因不在打包，而在**运行环境**：
//
//    ① 环境里残留 ELECTRON_RUN_AS_NODE=1
//       → Electron 退化成纯 Node：不加载 app、不起窗口、
//         把 --no-sandbox 报成 "bad option"、静默退出
//
//    ② 需要 --no-sandbox
//       → 这个环境里 Electron 沙箱初始化触发 STATUS_ACCESS_VIOLATION
//         （实测：未打包的原始 electron.exe 同样崩溃）
//
//    ③ 需要 --disable-gpu 等开关
//       → 规避 GPU 初始化失败
//
//  源码版没事，是因为 `启动.vbs` → `启动.ps1` 里做了这三件事。
//  打包版没有脚本，所以全丢了。
//
//  这个钩子：打包完在 exe 旁边生成一个 `.cmd` 启动器，
//  它先清环境变量、再带全部开关启动 exe。
//  用户双击这个 .cmd 就能用（也可以给它改名字/图标）。
//
//  ⚠ 这是一个**环境适配方案**，不是理想方案。
//     理想方案是 exe 自己就能起（需要修环境或换 Electron 版本）。
//     当前方案的价值是「先能跑起来」，代价是多一个 .cmd 文件。
// ══════════════════════════════════════════════════════════════════════

const fs = require('fs');
const path = require('path');

// ══════════════════════════════════════════════════════════════════════
//  复制引擎的 node_modules（2026-11-13 加 —— 这是打包最麻烦的一步）
// ══════════════════════════════════════════════════════════════════════
//
//  问题：electron-builder 的 extraResources **永远不会**把
//        `引擎/node_modules` 复制进去，无论 filter 怎么写。
//        实测了 3 次：
//          ① filter: ['**/*']                    → node_modules 缺失
//          ② filter: ['**/*','node_modules/**/*'] → 仍然缺失
//          ③ 加 dot: true                         → 仍然缺失
//
//        原因：electron-builder 内部对 node_modules 有硬编码的排除规则
//        （它认为 node_modules 该由它自己的依赖收集逻辑处理，
//          而引擎是 extraResources，不在它的依赖树里）。
//
//  后果：CLI_BUILT = 引擎/node_modules/@deepseek-ai/dsh-desktop-host/lib/cli.js
//        找不到 → 引擎起不来 → 界面显示「会话列表暂不可用」
//
//  解法：在 afterPack 里**手动复制**。这是唯一可靠的方式。
//
//  代价：引擎 node_modules 有 428 MB，复制会让打包慢 20~40 秒，
//        产物从 468 MB 涨到约 900 MB。但引擎没有它就是个空壳。
//
//  ⚠ 这是一个「绕过工具限制」的补丁，不是理想做法。
//    如果将来 electron-builder 支持了，应该删掉这段。
// ══════════════════════════════════════════════════════════════════════
function copyEngineNodeModules(context) {
  const outDir = context.appOutDir;
  const resDir = path.join(outDir, 'resources');
  const target = path.join(resDir, '引擎', 'node_modules');
  const src = path.resolve(__dirname, '..', '..', '引擎', 'node_modules');

  if (!fs.existsSync(src)) {
    console.log('[afterPack] 源引擎没有 node_modules，跳过');
    return;
  }
  if (fs.existsSync(path.join(target, '@deepseek-ai', 'dsh-desktop-host', 'lib', 'cli.js'))) {
    console.log('[afterPack] 引擎 node_modules 已存在，跳过复制');
    return;
  }

  console.log('[afterPack] 开始复制引擎 node_modules（428 MB，需要 20~40 秒）…');
  const t0 = Date.now();
  try {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    if (typeof fs.cpSync === 'function') {
      fs.cpSync(src, target, { recursive: true, force: true });
    } else {
      throw new Error('Node 版本过低，没有 fs.cpSync');
    }
    const sec = Math.round((Date.now() - t0) / 1000);
    // 验证关键文件真的存在
    const cli = path.join(target, '@deepseek-ai', 'dsh-desktop-host', 'lib', 'cli.js');
    if (fs.existsSync(cli)) {
      console.log('[afterPack] ✓ 引擎 node_modules 复制完成（' + sec + ' 秒）');
      console.log('[afterPack] ✓ CLI 已验证: ' + (fs.statSync(cli).size) + ' 字节');
    } else {
      console.log('[afterPack] ⛔ 复制完成但 CLI 仍不存在！引擎将无法启动');
      console.log('[afterPack]    期望: ' + cli);
    }
  } catch (e) {
    console.log('[afterPack] ⛔ 复制引擎 node_modules 失败: ' + (e && e.message));
    console.log('[afterPack]    打包产物将无法启动引擎。');
  }
}

exports.default = async function afterPack(context) {
  // ① 先补引擎依赖（这是能不能跑起来的关键）
  copyEngineNodeModules(context);

  const outDir = context.appOutDir;
  const exeName = 'DSH 工作台.exe';
  const exePath = path.join(outDir, exeName);

  if (!fs.existsSync(exePath)) {
    console.log('[afterPack] 找不到 exe，跳过启动器生成:', exePath);
    return;
  }

  // ── 生成 .cmd 启动器 ──
  //
  // ⚠ 2026-11-13 修（中文文件名在 latin1 编码下变乱码，exe 找不到）
  //
  //   第一版：fs.writeFileSync(cmdPath, cmd, 'latin1')
  //           cmd 里写 `start "" "DSH 工作台.exe" ...`
  //   实测产物：`start "" "DSH ?\?.exe" ...`  ← 三个中文字变问号
  //           → start 找不到文件 → 什么都没发生（连报错都没有）
  //
  //   根因：latin1 不能表示中文。cmd 是 ANSI 编码解释的，
  //        而中文 Windows 的 ANSI 是 GBK（936）。
  //
  //   修法：① 文件内容全用 ASCII（不写中文进 cmd）
  //        ② exe 名改用通配符 `DSH*.exe`，避免写中文
  //        ③ 注释也用英文
  const cmd = [
    '@echo off',
    'rem ============================================================',
    'rem  DSH Workbench launcher',
    'rem  Generated by electron-builder afterPack hook. Do not edit.',
    'rem ============================================================',
    'setlocal',
    '',
    'rem (1) CRITICAL: this env var makes Electron run as plain Node.',
    'rem     Note: `set VAR=` (empty) actually REMOVES the variable in cmd.',
    'set ELECTRON_RUN_AS_NODE=',
    '',
    'rem (2) Skip the single-instance lock.',
    'rem     On some machines Electron cannot create SingletonLock',
    'rem     (it uses a symlink; error code 3 = ERROR_PATH_NOT_FOUND).',
    'rem     Without this the app quits silently and nothing shows up.',
    'set DSH_SKIP_SINGLE_LOCK=1',
    '',
    'rem (3) cd to this script dir (path may contain spaces / CJK)',
    'cd /d "%~dp0"',
    '',
    'rem (4) Launch.',
    'rem     Use a wildcard so this file stays pure ASCII',
    'rem     (the exe name is CJK and would be mangled by ANSI encoding).',
    'rem',
    'rem     NOTE: `start` creates a NEW process that does NOT inherit variables',
    'rem     from `setlocal`. That is why we pass the env var via cmd /c instead',
    'rem     of relying on `set` alone -- this is the bug that made the first',
    'rem     launcher silently fail even though DSH_SKIP_SINGLE_LOCK was set.',
    'rem     --no-sandbox : sandbox init crashes on this machine',
    'rem     --disable-gpu* : avoid GPU init failure',
    'for %%F in ("DSH*.exe") do (',
    '  start "" cmd /c "set DSH_SKIP_SINGLE_LOCK=1&& set ELECTRON_RUN_AS_NODE=&& "%%~fF" --no-sandbox --disable-gpu --disable-gpu-compositing --disable-software-rasterizer"',
    ')',
    '',
    'endlocal',
  ].join('\r\n');

  const cmdPath = path.join(outDir, 'START-DSH.cmd');
  try {
    fs.writeFileSync(cmdPath, cmd, 'ascii');
    console.log('[afterPack] 启动器已生成:', path.basename(cmdPath), '(ASCII 安全)');
  } catch (e) {
    console.log('[afterPack] 生成启动器失败:', e && e.message);
  }

  // ── 同时写一份 README 说明为什么要用启动器 ──
  const readme = [
    'DSH 工作台 —— 启动说明',
    '='.repeat(40),
    '',
    '怎么启动：双击「启动 DSH 工作台.cmd」',
    '',
    '为什么不直接双击 exe：',
    '  exe 就是 Electron 本体，但当前这台机器有两个环境问题：',
    '',
    '  1) 系统里可能残留环境变量 ELECTRON_RUN_AS_NODE=1',
    '     它会让 Electron 退化成纯 Node —— 不加载界面、静默退出。',
    '     启动器会先清掉它。',
    '',
    '  2) 这台机器的 Electron 沙箱初始化会崩溃（STATUS_ACCESS_VIOLATION）',
    '     启动器加了 --no-sandbox 规避。',
    '',
    '  这两条都是**环境适配**，不是程序本身的缺陷。',
    '  在干净的桌面环境里，直接双击 exe 应该也能用。',
    '',
    '数据在哪：',
    '  %APPDATA%\\DSH工作台\\',
    '    数据\\        场景记忆、技能、产物（你的积累，升级不会覆盖）',
    '    boot.log     启动日志（出问题先看这个）',
    '',
    '卸载：',
    '  用「添加或删除程序」卸载。你的数据会保留在 %APPDATA%\\DSH工作台\\。',
    '',
  ].join('\r\n');

  try {
    fs.writeFileSync(path.join(outDir, 'README-START.txt'), readme, 'utf8');
    console.log('[afterPack] 启动说明已生成: README-START.txt');
  } catch (e) {
    console.log('[afterPack] 生成说明失败:', e && e.message);
  }
};
