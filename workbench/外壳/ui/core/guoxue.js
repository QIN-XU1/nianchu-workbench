/**
 * 判断场景当前处于五行哪个阶段
 *
 * 依据（不是猜的）：
 *   无会话               → 木（待创建/待生发）
 *   有会话但无产物        → 火（正在执行）
 *   有产物但记忆未写回    → 土（待汇总）
 *   有产物且记忆已写回    → 金（待归档）
 *   有归档且无新任务      → 水（已沉淀）
 */
export function inferPhase(sceneState) {
  const s = sceneState || {};
  if (!s.hasSession) return Wuxing[0];                      // 木·生
  if (s.running) return Wuxing[1];                          // 火·长
  if (!s.hasArtifact) return Wuxing[1];                     // 火·长
  if (!s.memoryOk) return Wuxing[2];                        // 土·化
  if (!s.archived) return Wuxing[3];                        // 金·收
  return Wuxing[4];                                         // 水·藏
}

/** 五行相生的下一个阶段 */
export function nextPhase(wuxingId) {
  const i = Wuxing.findIndex(function (w) { return w.id === wuxingId; });
  if (i < 0) return null;
  return Wuxing[(i + 1) % Wuxing.length];
}

