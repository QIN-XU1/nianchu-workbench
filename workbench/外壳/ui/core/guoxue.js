/** 根据文件路径判断属于哪一层（用于场景详情面板显示） */
export function whichLayer(pathStr) {
  const s = String(pathStr || '');
  if (/AGENTS\.md$/i.test(s)) return Sancai.tian;
  if (/_共享记忆/.test(s)) return Sancai.ren;
  if (/场景记忆/.test(s)) return Sancai.di;
  return null;
}

